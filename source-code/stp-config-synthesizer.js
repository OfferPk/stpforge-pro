/**
 * STPForge Pro - Multi-Platform Configuration Synthesizer
 * Generates verified production syntax for:
 * 1. Cisco IOS-XE / NX-OS
 * 2. Arista EOS
 * 3. Juniper Junos
 * 4. Linux / Cumulus / SONiC (mstpd)
 * 5. Prometheus Telemetry Alerting Rules
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.STPConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function generateCisco(cfg) {
    const lines = [];
    const isMst = cfg.protocolMode === 'MSTP';
    const stpMode = isMst ? 'mst' : 'rapid-pvst';
    const prio = cfg.rootPriority || 0;

    lines.push('! ==============================================================================');
    lines.push('! Cisco IOS-XE / NX-OS Hardened Spanning Tree Configuration');
    lines.push('! Generated by STPForge Pro v1.0.0 (IEEE 802.1w / 802.1s)');
    lines.push('! ==============================================================================');
    lines.push('!');
    lines.push(`spanning-tree mode ${stpMode}`);
    if (isMst) {
      lines.push('spanning-tree mst configuration');
      lines.push(` name ${cfg.mstRegionName || 'CORP-FABRIC-01'}`);
      lines.push(` revision ${cfg.mstRevision || 1}`);
      lines.push(' instance 1 vlan 10-99');
      lines.push(' instance 2 vlan 100-199');
      lines.push('!');
      lines.push(`spanning-tree mst 0-2 priority ${prio}`);
    } else {
      lines.push(`spanning-tree vlan 1-4094 priority ${prio}`);
    }
    lines.push('');
    lines.push('! --- Global Zero-Trust Protection Defaults ---');
    if (cfg.bpduGuardEnabled) {
      lines.push('spanning-tree portfast default');
      lines.push('spanning-tree portfast bpduguard default');
    }
    if (cfg.loopGuardEnabled) {
      lines.push('spanning-tree loopguard default');
    }
    lines.push('');
    lines.push('! --- Downstream Distribution / Access Facing Links ---');
    lines.push('interface range GigabitEthernet1/0/1 - 48');
    lines.push(' description Access Edge Ports');
    if (cfg.bpduGuardEnabled) {
      lines.push(' spanning-tree portfast');
      lines.push(' spanning-tree bpduguard enable');
    }
    lines.push('!');
    lines.push('! --- Inter-Switch Core Trunks (Root Guard & P2P) ---');
    lines.push('interface TenGigabitEthernet1/1/1');
    lines.push(' description Inter-Switch Trunk to Distribution/Spine');
    lines.push(' switchport mode trunk');
    lines.push(' spanning-tree link-type point-to-point');
    if (cfg.rootGuardEnabled) {
      lines.push(' spanning-tree guard root');
    }
    lines.push('!');
    if (cfg.borderBpduFilter) {
      lines.push('! --- External Carrier / WAN Border Uplink ---');
      lines.push('interface GigabitEthernet1/0/48');
      lines.push(' description External WAN Handoff (Fault Isolation)');
      lines.push(' spanning-tree bpdufilter enable');
      lines.push('!');
    }
    return lines.join('\n');
  }

  function generateArista(cfg) {
    const lines = [];
    const isMst = cfg.protocolMode === 'MSTP';
    const stpMode = isMst ? 'mst' : 'rapid-pvst';
    const prio = cfg.rootPriority || 0;

    lines.push('! ==============================================================================');
    lines.push('! Arista EOS Hardened Spanning Tree Configuration');
    lines.push('! Generated by STPForge Pro v1.0.0');
    lines.push('! ==============================================================================');
    lines.push('!');
    lines.push(`spanning-tree mode ${stpMode}`);
    if (isMst) {
      lines.push('spanning-tree mst configuration');
      lines.push(`   name ${cfg.mstRegionName || 'CORP-FABRIC-01'}`);
      lines.push(`   revision ${cfg.mstRevision || 1}`);
      lines.push('   instance 1 vlan 10-99');
      lines.push('   instance 2 vlan 100-199');
      lines.push('!');
      lines.push(`spanning-tree mst 0-2 priority ${prio}`);
    } else {
      lines.push(`spanning-tree priority ${prio}`);
    }
    lines.push('!');
    if (cfg.bpduGuardEnabled) {
      lines.push('spanning-tree edge-port bpduguard default');
    }
    lines.push('!');
    lines.push('interface Ethernet1-48');
    lines.push('   comment End-User Access Ports');
    lines.push('   spanning-tree portfast');
    if (cfg.bpduGuardEnabled) {
      lines.push('   spanning-tree bpduguard enable');
    }
    lines.push('!');
    lines.push('interface Ethernet49/1');
    lines.push('   comment Spine Interconnect Trunk');
    if (cfg.rootGuardEnabled) {
      lines.push('   spanning-tree guard root');
    }
    lines.push('   spanning-tree link-type point-to-point');
    lines.push('!');
    return lines.join('\n');
  }

  function generateJunos(cfg) {
    const lines = [];
    const isMst = cfg.protocolMode === 'MSTP';
    const prio = cfg.rootPriority || 0;

    lines.push('# ==============================================================================');
    lines.push('# Juniper Junos Spanning Tree Configuration');
    lines.push('# Generated by STPForge Pro v1.0.0');
    lines.push('# ==============================================================================');
    lines.push('');
    if (isMst) {
      lines.push('set protocols mstp configuration-name ' + (cfg.mstRegionName || 'CORP-FABRIC-01'));
      lines.push('set protocols mstp revision-level ' + (cfg.mstRevision || 1));
      lines.push(`set protocols mstp bridge-priority ${prio}`);
    } else {
      lines.push(`set protocols rstp bridge-priority ${prio}`);
    }
    lines.push('');
    if (cfg.bpduGuardEnabled) {
      lines.push('# Global Edge BPDU Block (BPDU Guard equivalent)');
      lines.push('set protocols rstp bpdu-block-on-edge');
      lines.push('set protocols rstp interface "ge-0/0/[0-47]" edge');
    }
    lines.push('');
    lines.push('# Core Trunk with Root Guard & Point-to-Point');
    lines.push('set protocols rstp interface xe-0/1/0.0 link-mode point-to-point');
    if (cfg.rootGuardEnabled) {
      lines.push('set protocols rstp interface xe-0/1/0.0 no-root-port');
    }
    return lines.join('\n');
  }

  function generateLinux(cfg) {
    const lines = [];
    lines.push('# ==============================================================================');
    lines.push('# Linux / Cumulus / SONiC Spanning Tree (mstpd)');
    lines.push('# Generated by STPForge Pro v1.0.0');
    lines.push('# ==============================================================================');
    lines.push('');
    lines.push('mstpctl setbridgeprio br0 ' + (cfg.rootPriority || 0));
    lines.push('mstpctl setfdelay br0 ' + (cfg.forwardDelay || 15));
    lines.push('mstpctl setmaxage br0 ' + (cfg.maxAge || 20));
    lines.push('');
    if (cfg.bpduGuardEnabled) {
      lines.push('# Configure Edge Ports with BPDU Guard');
      lines.push('for port in $(seq 1 24); do');
      lines.push('    mstpctl setportedge br0 eth${port} yes');
      lines.push('    mstpctl setportbpduguard br0 eth${port} yes');
      lines.push('done');
    }
    lines.push('');
    lines.push('# Point-to-Point Uplinks with Network Port Protection');
    lines.push('mstpctl setportp2p br0 eth49 yes');
    if (cfg.rootGuardEnabled) {
      lines.push('mstpctl setportnetwork br0 eth49 yes # Bridge Assurance / Root Protection');
    }
    return lines.join('\n');
  }

  function generatePrometheus(cfg) {
    return `# ==============================================================================
# Prometheus Spanning Tree & L2 Telemetry Alerting Rules
# Generated by STPForge Pro v1.0.0
# ==============================================================================

groups:
  - name: stp_telemetry_alerts
    rules:
      - alert: STPTopologyChangeRateHigh
        expr: rate(stp_topology_changes_total[2m]) > 5
        for: 1m
        labels:
          severity: critical
          tier: layer2-core
        annotations:
          summary: "Excessive Spanning Tree Topology Changes on {{ $labels.instance }}"
          description: "High rate of TC BPDUs detected. MAC tables are flushing rapidly, causing unicast broadcast flooding."

      - alert: STPRootBridgeElectionFlap
        expr: changes(stp_root_bridge_mac[5m]) > 2
        for: 30s
        labels:
          severity: critical
          tier: layer2-core
        annotations:
          summary: "Spanning Tree Root Bridge Flapping Detected!"
          description: "Root Bridge identity has changed multiple times in the last 5 minutes. High probability of rogue switch injection or Root Guard triggering."

      - alert: STPPortInconsistentStateAlert
        expr: stp_port_state{state="root_inconsistent"} == 1
        for: 1m
        labels:
          severity: warning
          tier: access-security
        annotations:
          summary: "Root Guard Blocked Superior BPDU on {{ $labels.interface }}"
          description: "Interface {{ $labels.interface }} transitioned to Root-Inconsistent (blocked) after receiving an unauthorized superior BPDU."

      - alert: STPBpduGuardErrDisabledAlert
        expr: stp_bpduguard_errdisabled_ports > 0
        for: 30s
        labels:
          severity: warning
          tier: edge-security
        annotations:
          summary: "Access Port Err-Disabled by BPDU Guard"
          description: "Rogue BPDU detected on user-facing edge port {{ $labels.interface }}. Port placed in err-disable state to protect network topology."
`;
  }

  return {
    generateCisco,
    generateArista,
    generateJunos,
    generateLinux,
    generatePrometheus
  };
}));
